/*
1. ПОДГОТОВКА СПРАЙТ-ЛИСТА:
   
   Ваш спрайт-лист должен быть organized в виде сетки кадров.
   Пример структуры:
   
   Row 0: [Idle 0] [Idle 1] [Idle 2] [Idle 3] [empty] [empty] [empty] [empty]
   Row 1: [Run 0]  [Run 1]  [Run 2]  [Run 3]  [Run 4] [Run 5] [Run 6] [Run 7]
   Row 2: [Jump 0] [Jump 1] [Fall 0] [Fall 1] [Climb 0] [Climb 1] [Climb 2] [Climb 3]
   Row 3: [Attack Melee 0] [Attack Melee 1] [Attack Melee 2] [Attack Melee 3] ...
   ...
   
   Каждый кадр должен быть одинакового размера.

2. РАЗМЕЩЕНИЕ ФАЙЛА:
   
   Поместите ваш спрайт-лист в папку: public/sprites/player_spritesheet.png
   
   Или измените путь в функции createPlayerSpriteSheet() выше.

3. НАСТРОЙКА ПАРАМЕТРОВ:
   
   В функции createPlayerSpriteSheet() измените:
   - Путь к изображению
   - frameWidth: ширина одного кадра (например, 64, 128, 256)
   - frameHeight: высота одного кадра (обычно равна frameWidth)
   - columns: количество колонок в вашем спрайт-листе
   - rows: количество строк в вашем спрайт-листе

4. НАСТРОЙКА АНИМАЦИЙ:
   
   Для каждой анимации укажите:
   - Название (должно совпадать с названиями в Player.ts)
   - Начальный кадр (номер кадра, начиная с 0)
   - Конечный кадр (номер кадра, включительно)
   - Скорость (кадров в секунду)
   - Зацикливание (true/false)
   
   Номера кадров считаются слева направо, сверху вниз:
   - Кадр 0: колонка 0, строка 0
   - Кадр 1: колонка 1, строка 0
   - Кадр 8: колонка 0, строка 1 (если columns = 8)
   - И так далее...

5. ПРИМЕР РАСЧЁТА НОМЕРОВ КАДРОВ:
   
   Если ваш спрайт-лист имеет 8 колонок и 8 строк:
   
   Row 0: кадры 0-7
   Row 1: кадры 8-15
   Row 2: кадры 16-23
   Row 3: кадры 24-31
   Row 4: кадры 32-39
   Row 5: кадры 40-47
   Row 6: кадры 48-55
   Row 7: кадры 56-63

6. ТЕСТИРОВАНИЕ:
   
   После настройки запустите игру и проверьте:
   - Все анимации отображаются корректно
   - Переходы между анимациями плавные
   - Направление персонажа (влево/вправо) работает
   - Размеры спрайтов соответствуют hitbox игрока

7. ОТЛАДКА:
   
   Если анимации не работают:
   - Проверьте консоль браузера на ошибки загрузки изображения
   - Убедитесь, что путь к файлу правильный
   - Проверьте, что номера кадров соответствуют вашей сетке
   - Убедитесь, что размеры кадров указаны правильно
*/

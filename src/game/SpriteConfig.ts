import { SpriteSheet } from './SpriteSheet';

// Пример конфигурации для вашего спрайт-листа
// Замените пути и параметры на свои значения

export function createPlayerSpriteSheet(): SpriteSheet {
  // Создаём спрайт-лист
  // Параметры:
  // - Путь к изображению (положите ваш спрайт-лист в папку public/sprites/)
  // - Ширина одного кадра (в пикселях)
  // - Высота одного кадра (в пикселях)
  // - Количество колонок в спрайт-листе
  // - Количество строк в спрайт-листе
  
  const spriteSheet = new SpriteSheet(
    '/sprites/player_spritesheet.png', // Путь к вашему спрайт-листу
    64,  // Ширина кадра (замените на ваш размер)
    64,  // Высота кадра (замените на ваш размер)
    6,   // Количество колонок (замените на ваше значение)
    5    // Количество строк (замените на ваше значение)
  );

  // Добавляем анимации
  // Параметры:
  // - Название анимации
  // - Начальный номер кадра (0-based)
  // - Конечный номер кадра (0-based, включительно)
  // - Скорость анимации (кадров в секунду)
  // - Зацикливать ли анимацию

  // Idle (стояние на месте)
  spriteSheet.addAnimation('idle', 0, 3, 8, true); // Кадры 0-3, 8 FPS, зациклено

  // Run (бег)
  spriteSheet.addAnimation('run', 8, 15, 12, true); // Кадры 8-15, 12 FPS, зациклено

  // Jump (прыжок)
  spriteSheet.addAnimation('jump', 16, 17, 8, false); // Кадры 16-17, 8 FPS, не зациклено

  // Fall (падение)
  spriteSheet.addAnimation('fall', 18, 19, 8, false); // Кадры 18-19, 8 FPS, не зациклено

  // Climb (лазание по лестнице)
  spriteSheet.addAnimation('climb', 20, 23, 8, true); // Кадры 20-23, 8 FPS, зациклено

  // Attack Melee (атака ближнего боя)
  spriteSheet.addAnimation('attack_melee', 24, 27, 15, false); // Кадры 24-27, 15 FPS, не зациклено

  // Attack Shoot (атака дальнего боя)
  spriteSheet.addAnimation('attack_shoot', 28, 30, 12, false); // Кадры 28-30, 12 FPS, не зациклено

  // Hurt (получение урона)
  spriteSheet.addAnimation('hurt', 32, 33, 10, false); // Кадры 32-33, 10 FPS, не зациклено

  // Death (смерть)
  spriteSheet.addAnimation('death', 40, 45, 8, false); // Кадры 40-45, 8 FPS, не зациклено

  return spriteSheet;
}

